#!/usr/bin/env node
/* One-time builder for national/us-geo.js: simplified US state outlines (public-domain US Census TIGERweb)
   projected with national/proj.js (Albers USA with Alaska, Hawaii and Puerto Rico insets). Node 18+. */
'use strict';
const fs = require('fs');
const path = require('path');
const P = require('../national/proj.js');
const URL_ = 'https://tigerweb.geo.census.gov/arcgis/rest/services/TIGERweb/State_County/MapServer/0/query?where=1%3D1&outFields=STUSAB,NAME&returnGeometry=true&maxAllowableOffset=0.02&geometryPrecision=3&f=geojson';
const W = 975, H = 610;
const PARTS = [
  { id: 'L48', lat1: 29.5, lat2: 45.5, lat0: 37.5, lon0: -96 },
  { id: 'AK', lat1: 55, lat2: 65, lat0: 50, lon0: -154 },
  { id: 'HI', lat1: 8, lat2: 18, lat0: 3, lon0: -157 },
  { id: 'PR', lat1: 18, lat2: 18.5, lat0: 18, lon0: -66.4 }
];
const stateTo = { AK: 'AK', HI: 'HI', PR: 'PR' };
const SKIP = new Set(['GU', 'AS', 'MP', 'VI']);
function rings(g) { return g.type === 'Polygon' ? [g.coordinates] : g.coordinates; }
(async () => {
  const gj = await (await fetch(URL_)).json();
  const feats = gj.features.filter((f) => !SKIP.has(f.properties.STUSAB));
  // raw projection per part to fit each inset into a box
  const raw = {};
  PARTS.forEach((p) => { raw[p.id] = { p: Object.assign({ k: 1, tx: 0, ty: 0 }, p), minx: 1e9, maxx: -1e9, miny: 1e9, maxy: -1e9 }; });
  const projRaw = P.make({ parts: PARTS.map((p) => Object.assign({ k: 1, tx: 0, ty: 0 }, p)), stateTo });
  feats.forEach((f) => {
    const st = f.properties.STUSAB, id = stateTo[st] || 'L48', b = raw[id];
    rings(f.geometry).forEach((poly) => poly.forEach((ring) => ring.forEach((c) => {
      if (id === 'L48' && c[0] > -60) return;
      const xy = projRaw(c[0], c[1], st); b.minx = Math.min(b.minx, xy[0]); b.maxx = Math.max(b.maxx, xy[0]); b.miny = Math.min(b.miny, xy[1]); b.maxy = Math.max(b.maxy, xy[1]);
    })));
  });
  // L48 fills the canvas; insets sit bottom-left (AK, HI) and bottom-right (PR)
  const l = raw.L48, k48 = Math.min((W - 20) / (l.maxx - l.minx), (H - 20) / (l.maxy - l.miny));
  const set = (id, k, x0, y0) => { const b = raw[id]; b.p.k = k; b.p.tx = x0 - b.minx * k; b.p.ty = y0 - b.miny * k; };
  set('L48', k48, 10 + ((W - 20) - (l.maxx - l.minx) * k48) / 2, 10);
  const akw = 150, hiw = 85, prw = 55;
  const ak = raw.AK, hi = raw.HI, pr = raw.PR;
  const akk = akw / (ak.maxx - ak.minx); set('AK', akk, 12, H - 14 - (ak.maxy - ak.miny) * akk);
  const hik = hiw / (hi.maxx - hi.minx); set('HI', hik, 12 + akw + 18, H - 14 - (hi.maxy - hi.miny) * hik);
  const prk = prw / (pr.maxx - pr.minx); set('PR', prk, W - 14 - prw, H - 14 - (pr.maxy - pr.miny) * prk);
  const proj = { w: W, h: H, parts: PARTS.map((p) => { const b = raw[p.id].p; return { id: p.id, lat1: p.lat1, lat2: p.lat2, lat0: p.lat0, lon0: p.lon0, k: +b.k.toFixed(4), tx: +b.tx.toFixed(2), ty: +b.ty.toFixed(2) }; }), stateTo };
  const pr_ = P.make(proj);
  const states = {};
  feats.forEach((f) => {
    const st = f.properties.STUSAB; let d = ''; let sx = 0, sy = 0, n = 0, best = 0, bx = 0, by = 0;
    rings(f.geometry).forEach((poly) => poly.forEach((ring, ri) => {
      const pts = ring.map((c) => pr_(c[0], c[1], st)).filter((p) => isFinite(p[0]));
      // drop tiny rings (islands under ~2 px wide) except when the state would vanish
      let minx = 1e9, maxx = -1e9, miny = 1e9, maxy = -1e9; pts.forEach((p) => { minx = Math.min(minx, p[0]); maxx = Math.max(maxx, p[0]); miny = Math.min(miny, p[1]); maxy = Math.max(maxy, p[1]); });
      const area = (maxx - minx) * (maxy - miny);
      if (ri === 0 && area < 3 && st !== 'DC') return;
      if (ri === 0 && area > best) { best = area; bx = (minx + maxx) / 2; by = (miny + maxy) / 2; }
      let last = null, s = '';
      pts.forEach((p) => { const x = +p[0].toFixed(1), y = +p[1].toFixed(1); if (last && Math.abs(last[0] - x) < 0.35 && Math.abs(last[1] - y) < 0.35) return; s += (s ? 'L' : 'M') + x + ' ' + y; last = [x, y]; });
      if (s) d += s + 'Z';
    }));
    states[st] = { n: f.properties.NAME, d, cx: +bx.toFixed(1), cy: +by.toFixed(1) };
  });
  const out = '/* Generated by scripts/build-us-geo.js from US Census TIGERweb state boundaries (public domain), generalized. Do not edit. */\nwindow.US_GEO = ' + JSON.stringify({ proj, states }) + ';\n';
  fs.writeFileSync(path.join(__dirname, '..', 'national', 'us-geo.js'), out);
  console.log('states', Object.keys(states).length, (out.length / 1024).toFixed(0) + ' KB');
})();
